const STRINGS = {
  'en-US': enUS,
  'en-GB': { ...enUS }, // UK English shares this game's vocabulary with en-US
  'es-419': es419,
  'es-ES': esES,
  'de-DE': deDE,
  'fr-FR': frFR,
  'fr-CA': frCA,
  'pt-BR': ptBR,
  'it-IT': itIT,
};

let current = 'en-US';

export function setLocale(tag) {
  if (STRINGS[tag]) current = tag;
}

export function currentLocale() {
  return current;
}

// Pick the best locale for a list of language tags (navigator.languages).
export function detectLocale(languages = []) {
  for (const tag of languages) {
    if (STRINGS[tag]) return tag;
  }
  for (const tag of languages) {
    const base = String(tag).split('-')[0];
    const hit = LOCALES.find((l) => l.split('-')[0] === base);
    if (hit) return hit;
  }
  return 'en-US';
}

// Resolve a string in the current locale with {var} interpolation,
// falling back to en-US and finally to the key itself.
export function t(key, vars = null) {
  let s = STRINGS[current]?.[key] ?? enUS[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

// Resolved dictionaries (locale + en-US fallback) for tests and tooling.
export function resolvedStrings(tag) {
  return { ...enUS, ...(STRINGS[tag] || {}) };
}
